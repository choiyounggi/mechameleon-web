import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
await page.goto('http://localhost:3000');
await page.fill('input[aria-label="닉네임"]', '호스트');
await page.fill('input[aria-label="방 이름"]', '실전');
await page.click('button.mc-btn:has-text("만들기")');
await page.waitForSelector('.mc-room-screen');
const p2 = await browser.newPage(); await p2.goto('http://localhost:3000');
await p2.fill('input[aria-label="닉네임"]', '멤버1'); await p2.click('button.mc-room-card');
await page.fill('input[aria-label="배경 URL"]', 'https://example.com');
await page.click('button:has-text("가져오기")');
await page.waitForSelector('img[alt="배경 미리보기"]', { timeout: 30000 });
await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent === '시작')?.disabled);
await page.click('button:has-text("시작")');
await page.waitForTimeout(1200);
const hostScreen = await page.evaluate(() => document.body.innerText.slice(0, 80).replace(/\n/g, ' | '));
const guestScreen = await p2.evaluate(() => document.body.innerText.slice(0, 80).replace(/\n/g, ' | '));
console.log('HOST:', JSON.stringify(hostScreen));
console.log('GUEST:', JSON.stringify(guestScreen));
await page.screenshot({ path: '.claude/tmp/game-started.png' });
await browser.close();
